test('the uploaded viewer defines exactly three distinct container types',()=>{
 assert.deepEqual(Types.all.map(x=>x.id),['maritimo','reefer','modular']);
 assert.deepEqual(Types.byId.maritimo.dims,[12.03,2.35,2.39]);
 assert.deepEqual(Types.byId.reefer.dims,[12.19,2.44,2.5]);
 assert.deepEqual(Types.byId.modular.dims,[5.95,2.43,2.5]);
 assert.equal(Types.byId.reefer.ridge,0);
 assert.equal(Types.byId.reefer.sheet,.075);
 assert.equal(Types.byId.reefer.seam,.55);
 assert.equal(Types.byId.modular.floor,'vinyl');
 assert.equal(Types.byId.maritimo.floor,'wood');
 assert.equal(Types.byId.reefer.floor,'alu');
 assert.equal(Types.byId.maritimo.decoration.D,'doors');
 assert.equal(Types.byId.reefer.decoration.D,'machine');
 assert.equal(Types.byId.reefer.decoration.C,'doors');
 assert.deepEqual(Object.keys(Visual.FACES).sort(),['A','B','C','D']);
});
test('switching type resets incompatible openings and partitions atomically, recalculating BOM',()=>{
 const store=Bridge.createStore();
 store.dispatch({type:'opening/add',kind:'window',face:'A',width:1,height:.8,bottom:1,offset:0,bars:true});
 store.dispatch({type:'partition/add',length:1.2,height:2,x:0,z:0});
 const before=store.getProjection();
 const reefer=store.dispatch({type:'container/type',containerType:'reefer'});
 assert.equal(reefer.project.container.type,'reefer');
 assert.deepEqual(reefer.openings,[]);
 assert.deepEqual(reefer.partitions,[]);
 assert.deepEqual([reefer.project.container.length,reefer.project.container.width,reefer.project.container.height],[12.19,2.44,2.5]);
 assert.equal(store.getProjection().revision,reefer.revision);
 assert.equal(store.getProjection().quote.lines.find(x=>x.code==='WINDOW').qty,0);
 assert.notEqual(store.getProjection().quote.total,before.quote.total);
 const modular=store.dispatch({type:'container/type',containerType:'modular'});
 assert.equal(modular.project.container.type,'modular');
 assert.equal(modular.project.container.color,'#c3c8cb');
 assert.equal(store.getProjection().revision,modular.revision);
 const beforeInvalid=store.getState(),quote=store.getProjection();
 assert.throws(()=>store.dispatch({type:'container/type',containerType:'other'}),/inválido/);
 assert.deepEqual(store.getState(),beforeInvalid);
 assert.deepEqual(store.getProjection(),quote);
});
test('barred windows are supported, malformed bars and barred doors rejected',()=>{
 const store=Bridge.createStore();
 store.dispatch({type:'container/type',containerType:'modular'});
 const state=store.dispatch({type:'opening/add',kind:'window',face:'A',width:1.2,height:1,bottom:1,offset:0,bars:true});
 assert.equal(state.openings[0].bars,true);
 const id=state.openings[0].id;
 const original=store.getState(),projection=store.getProjection();
 assert.throws(()=>store.dispatch({type:'opening/update',id,bars:'true'}),/inválidos/);
 assert.throws(()=>store.dispatch({type:'opening/update',id,kind:'door'}),/No se admiten/);
 assert.deepEqual(store.getState(),original);
 assert.deepEqual(store.getProjection(),projection);
 const after=store.dispatch({type:'opening/update',id,bars:false});
 assert.equal(after.openings[0].bars,false);
 assert.equal(store.getProjection().revision,after.revision);
});
test('clear openings does not change partitions and reprojects the price',()=>{
 const store=Bridge.createStore();
 store.dispatch({type:'opening/add',kind:'window',face:'A',width:1,height:1,bottom:.9,bars:true});
 store.dispatch({type:'partition/add',length:1,height:2,x:0,z:0});
 const previous=store.getState();
 const state=store.dispatch({type:'opening/clear'});
 assert.equal(state.openings.length,0);
 assert.equal(state.partitions.length,1);
 assert.equal(state.revision,previous.revision+1);
 assert.equal(store.getProjection().quote.lines.find(x=>x.code==='WINDOW').qty,0);
});
